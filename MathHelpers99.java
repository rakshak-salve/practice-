public class MathHelpers99 {
    public static int compute(int a) {
        return a * 2;
    }
    public static int compute(int a, int b) {
        return a + b;
    }
    public static void main(String[] args) {
        System.out.println(compute(5));
        System.out.println(compute(5, 10));
    }
}
